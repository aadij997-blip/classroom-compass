// Regenerates the Supabase content_items seed (option IDs only — never keys).
// Run after changing content/learning-content.json: node scripts/generate-content-seed.mjs
import fs from "node:fs";
const content = JSON.parse(fs.readFileSync(new URL("../content/learning-content.json", import.meta.url)));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs) => `array[${xs.map(q).join(",")}]`;
const rows = content.items.map(
  (i) => `  (${q(i.id)}, ${i.version}, ${q(i.concept_id)}, ${arr(i.answer_options.map((o) => o.id))}, ${arr(i.reason_options.map((o) => o.id))})`,
);
const sql = `-- Generated by scripts/generate-content-seed.mjs from content ${content.content_version}.
-- Option IDs only. Answer keys and mappings stay in server-only application code.
insert into public.content_items (item_id, version, concept_id, answer_ids, reason_ids) values
${rows.join(",\n")}
on conflict (item_id, version) do update set answer_ids = excluded.answer_ids, reason_ids = excluded.reason_ids;
`;
fs.writeFileSync(new URL("../supabase/migrations/20261124000002_content_items.sql", import.meta.url), sql);
console.log(`Wrote ${rows.length} item versions.`);
